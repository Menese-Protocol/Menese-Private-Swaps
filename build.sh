#!/usr/bin/env bash
# Reproducible build of the private-swap modules: the swap canister and the two pool upgrades.
#
#   SWAP_CANISTER_ID=<principal> ./build.sh [out-dir]
#   ./build.sh --upstream [out-dir]      # the unmodified live pool sources, to prove the method
#   ./build.sh --hardening [out-dir]     # the pools' hardening release H (HARDENING_SRC), which the
#                                        # swap package's pool upgrades follow
#
# moc embeds source paths in the module, so every module is compiled from a staging directory in
# the layout the live pools were built from: src/Main.mo with packages under .mops/<name>@<ver>/src,
# all paths relative. Compiler: moc 1.4.1; packages: core 1.0.0 and sha2 0.1.9 (vendored).
# The pools name the swap canister in their module (src/SwapConfig.mo, generated here), so the build
# refuses to run without its id.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
moc="${MOC:-moc}"
"$moc" --version | grep -q "1.4.1" || { echo "moc 1.4.1 required (MOC=...)"; exit 2; }
upstream=0
hardening=0
if [[ "${1:-}" == "--upstream" ]]; then upstream=1; shift; fi
if [[ "${1:-}" == "--hardening" ]]; then upstream=1; hardening=1; shift; fi
out="${1:-$here/out}"
rm -rf "$out"; mkdir -p "$out"
out="$(cd "$out" && pwd)"
stage() { # stage <dir>: an empty staging dir with the vendored packages
  rm -rf "$1"; mkdir -p "$1/.mops"
  cp -r "$here/vendor/core@1.0.0" "$here/vendor/sha2@0.1.9" "$1/.mops/"
}
pkgs=(--package sha2 .mops/sha2@0.1.9/src --package core .mops/core@1.0.0/src)
pool() { # pool <name> <icp:0|1> <src-dir>
  local d="$out/stage-$1"; stage "$d"
  cp -r "$3" "$d/src"
  if [[ "$2" == 1 ]]; then cp "$here/pool/icp-overrides/"*.mo "$d/src/"; fi
  if [[ "$upstream" == 0 ]]; then
    printf '/// Generated by build.sh: the swap canister this pool module serves.\nmodule {\n  public let SWAP_CANISTER : Text = "%s";\n};\n' "$SWAP_CANISTER_ID" > "$d/src/SwapConfig.mo"
  fi
  local meta=(--public-metadata candid:service)
  if [[ "$2" == 1 ]]; then meta+=(--public-metadata candid:args); fi
  ( cd "$d" && "$moc" "${pkgs[@]}" src/Main.mo "${meta[@]}" -o "$out/$1.wasm" 2>/dev/null )
  rm -rf "$d"
}
if [[ "$hardening" == 1 ]]; then
  [[ -d "${HARDENING_SRC:-}" ]] || { echo "HARDENING_SRC must name the hardening release's pool src/ (pool/src with pool/SWAP-DIFF.patch reversed)"; exit 2; }
  pool hardening-ckbtc 0 "$HARDENING_SRC"
  pool hardening-icp 1 "$HARDENING_SRC"
elif [[ "$upstream" == 1 ]]; then
  [[ -d "${UPSTREAM_SRC:-}" ]] || { echo "UPSTREAM_SRC must name the unmodified live ckBTC-pool src/ (mirror commit aa2a6e0f, module 4c26e066)"; exit 2; }
  pool upstream-ckbtc 0 "$UPSTREAM_SRC"
  pool upstream-icp 1 "$UPSTREAM_SRC"
else
  id="${SWAP_CANISTER_ID:-}"
  [[ "$id" =~ ^[a-z0-9]{5}(-[a-z0-9]{5}){3}-[a-z0-9]{3}$ ]] || { echo "SWAP_CANISTER_ID must be the swap canister's principal"; exit 2; }
  pool pool-ckbtc 0 "$here/pool/src"
  pool pool-icp 1 "$here/pool/src"
  d="$out/stage-swap"; stage "$d"
  cp -r "$here/canister/src" "$d/src"
  cp -r "$here/pool/src" "$d/zk"
  ( cd "$d" && "$moc" "${pkgs[@]}" --package zk zk src/Swap.mo --public-metadata candid:service --public-metadata candid:args -o "$out/swap.wasm" 2>/dev/null )
  ( cd "$d" && "$moc" "${pkgs[@]}" --package zk zk src/Swap.mo --idl -o "$out/swap.did" 2>/dev/null )
  rm -rf "$d"
fi
for w in "$out"/*.wasm; do gzip -n -9 -c "$w" > "$w.gz"; done
( cd "$out" && sha256sum *.wasm *.wasm.gz | tee SHA256SUMS )
